//! Linear framebuffer text console with an embedded 8x8 bitmap font.

use core::fmt::{self, Write};
use core::sync::atomic::{AtomicBool, Ordering};

use crate::limine::Framebuffer;

static FB_LOCK: AtomicBool = AtomicBool::new(false);
static mut CONSOLE: Option<FbConsole> = None;

struct FbConsole {
    addr: *mut u8,
    width: usize,
    height: usize,
    pitch: usize,
    bpp: usize,
    r_shift: u8,
    g_shift: u8,
    b_shift: u8,
    col: usize,
    row: usize,
    cols: usize,
    rows: usize,
    fg: (u8, u8, u8),
    bg: (u8, u8, u8),
}

impl FbConsole {
    fn pack_color(&self, r: u8, g: u8, b: u8) -> u32 {
        ((r as u32) << self.r_shift) | ((g as u32) << self.g_shift) | ((b as u32) << self.b_shift)
    }

    fn put_pixel(&mut self, x: usize, y: usize, color: u32) {
        if x >= self.width || y >= self.height || self.bpp != 32 {
            return;
        }
        let offset = y * self.pitch + x * 4;
        unsafe {
            let ptr = self.addr.add(offset) as *mut u32;
            core::ptr::write_volatile(ptr, color);
        }
    }

    fn clear(&mut self) {
        let bg = self.pack_color(self.bg.0, self.bg.1, self.bg.2);
        for y in 0..self.height {
            for x in 0..self.width {
                self.put_pixel(x, y, bg);
            }
        }
        self.col = 0;
        self.row = 0;
    }

    fn scroll_up(&mut self) {
        let line_bytes = 8 * self.pitch;
        let total_bytes = self.height * self.pitch;
        if total_bytes <= line_bytes {
            self.clear();
            return;
        }
        unsafe {
            core::ptr::copy(
                self.addr.add(line_bytes),
                self.addr,
                total_bytes - line_bytes,
            );
        }
        let bg = self.pack_color(self.bg.0, self.bg.1, self.bg.2);
        for y in (self.height - 8)..self.height {
            for x in 0..self.width {
                self.put_pixel(x, y, bg);
            }
        }
        self.row = self.rows.saturating_sub(1);
    }

    fn newline(&mut self) {
        self.col = 0;
        self.row += 1;
        if self.row >= self.rows {
            self.scroll_up();
        }
    }

    fn draw_char(&mut self, ch: u8) {
        match ch {
            b'\n' => {
                self.newline();
                return;
            }
            b'\r' => {
                self.col = 0;
                return;
            }
            _ => {}
        }

        if self.col >= self.cols {
            self.newline();
        }

        let glyph = glyph_8x8(ch);
        let fg = self.pack_color(self.fg.0, self.fg.1, self.fg.2);
        let bg = self.pack_color(self.bg.0, self.bg.1, self.bg.2);
        let px = self.col * 8;
        let py = self.row * 8;

        for (dy, row_bits) in glyph.iter().enumerate() {
            for dx in 0..8 {
                let on = (row_bits >> (7 - dx)) & 1 != 0;
                self.put_pixel(px + dx, py + dy, if on { fg } else { bg });
            }
        }

        self.col += 1;
    }
}

impl Write for FbConsole {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        for b in s.bytes() {
            self.draw_char(b);
        }
        Ok(())
    }
}

pub fn init(fb: &Framebuffer) {
    while FB_LOCK
        .compare_exchange_weak(false, true, Ordering::Acquire, Ordering::Relaxed)
        .is_err()
    {
        core::hint::spin_loop();
    }

    let width = fb.width as usize;
    let height = fb.height as usize;
    let mut console = FbConsole {
        addr: fb.address,
        width,
        height,
        pitch: fb.pitch as usize,
        bpp: fb.bpp as usize,
        r_shift: fb.red_mask_shift,
        g_shift: fb.green_mask_shift,
        b_shift: fb.blue_mask_shift,
        col: 0,
        row: 0,
        cols: (width / 8).max(1),
        rows: (height / 8).max(1),
        fg: (0xE6, 0xED, 0xF3),
        bg: (0x0D, 0x11, 0x17),
    };
    console.clear();
    unsafe {
        CONSOLE = Some(console);
    }

    FB_LOCK.store(false, Ordering::Release);
}

pub fn _print(args: fmt::Arguments) {
    while FB_LOCK
        .compare_exchange_weak(false, true, Ordering::Acquire, Ordering::Relaxed)
        .is_err()
    {
        core::hint::spin_loop();
    }
    unsafe {
        if let Some(ref mut console) = CONSOLE {
            let _ = console.write_fmt(args);
        }
    }
    FB_LOCK.store(false, Ordering::Release);
}

#[macro_export]
macro_rules! fb_print {
    ($($arg:tt)*) => {
        $crate::console::_print(format_args!($($arg)*))
    };
}

#[macro_export]
macro_rules! fb_println {
    () => ($crate::fb_print!("\n"));
    ($($arg:tt)*) => ($crate::fb_print!("{}\n", format_args!($($arg)*)));
}

